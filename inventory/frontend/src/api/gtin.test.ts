import { describe, expect, it } from 'vitest';
import { normalizeGtin } from './gtin';

describe('normalizeGtin', () => {
  it.each([
    ['4006381333931', '4006381333931'],
    [' 4006381333931 ', '4006381333931'],
    ['96385074', '96385074'],
    ['036000291452', '0036000291452'],
    ['04006381333931', '4006381333931'],
    ['14006381333938', '14006381333938'],
    ['01234505', '0012000003455'],
    ['01234133', '0012300000413'],
    ['01234543', '0012340000053'],
    ['11234502', '0112000003452'],
  ])('normalizes %s', (raw, expected) => expect(normalizeGtin(raw)).toBe(expected));

  it.each(['', '4006381333932', '400638133393A', '4006-381333931', '1234567', '123456789', '123456789012345',
    '036000291453', '24006381333931', '21234505', '01234506', '01234561'])('rejects "%s"', (raw) =>
    expect(normalizeGtin(raw)).toBeUndefined());
});
