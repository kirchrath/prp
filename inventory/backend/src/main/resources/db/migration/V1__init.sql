create table category
(
    id   bigint generated by default as identity primary key,
    name varchar(100) not null unique
);

create table storage_location
(
    id          bigint generated by default as identity primary key,
    name        varchar(100) not null,
    description varchar(500),
    parent_id   bigint references storage_location (id),
    constraint uq_location_name_per_parent unique nulls not distinct (parent_id, name)
);

create table article
(
    id           bigint generated by default as identity primary key,
    name         varchar(200) not null,
    brand        varchar(200),
    package_size varchar(100),
    image_url    varchar(1000),
    category_id  bigint references category (id) on delete set null,
    min_stock    integer      not null default 0 check (min_stock >= 0),
    status       varchar(20)  not null,
    source       varchar(30)  not null,
    created_at   timestamptz  not null,
    updated_at   timestamptz  not null
);

create index idx_article_status on article (status);

create table article_barcode
(
    article_id bigint      not null references article (id) on delete cascade,
    ean        varchar(64) not null unique,
    primary key (article_id, ean)
);

create table stock_batch
(
    id          bigint generated by default as identity primary key,
    article_id  bigint  not null references article (id),
    location_id bigint  not null references storage_location (id),
    best_before date,
    quantity    integer not null check (quantity > 0),
    constraint uq_batch unique nulls not distinct (article_id, location_id, best_before)
);

create index idx_batch_location on stock_batch (location_id);

create table scanner
(
    id               bigint generated by default as identity primary key,
    device_id        varchar(64) not null unique,
    name             varchar(100),
    location_id      bigint references storage_location (id) on delete set null,
    online           boolean     not null default false,
    firmware_version varchar(50),
    ip_address       varchar(64),
    last_seen        timestamptz,
    last_boot_id     varchar(64),
    last_seq         bigint,
    created_at       timestamptz not null
);

create table stock_movement
(
    id          bigint generated by default as identity primary key,
    article_id  bigint      not null references article (id) on delete cascade,
    location_id bigint      references storage_location (id) on delete set null,
    best_before date,
    delta       integer     not null,
    type        varchar(20) not null,
    source      varchar(20) not null,
    scanner_id  bigint      references scanner (id) on delete set null,
    username    varchar(100),
    created_at  timestamptz not null
);

create index idx_movement_created on stock_movement (created_at desc);
create index idx_movement_article on stock_movement (article_id);

create table shopping_list_item
(
    id         bigint generated by default as identity primary key,
    article_id bigint references article (id) on delete cascade,
    text       varchar(200),
    quantity   integer     not null default 1 check (quantity > 0),
    automatic  boolean     not null default false,
    done       boolean     not null default false,
    created_at timestamptz not null,
    constraint chk_item_content check (article_id is not null or text is not null)
);

create unique index uq_shopping_auto_article on shopping_list_item (article_id) where automatic;
